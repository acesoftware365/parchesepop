enum RetentionMilestone { day0, day1, day7, returning }

int onlineSearchElapsedMilliseconds({
  required DateTime startedAt,
  required DateTime now,
}) {
  final elapsed = now.difference(startedAt).inMilliseconds;
  return elapsed < 0 ? 0 : elapsed;
}

int onlineMatchmakingWaitSeconds(int elapsedMilliseconds) {
  if (elapsedMilliseconds <= 0) return 0;
  return (elapsedMilliseconds / 1000).round();
}

/// Optional opaque references used to correlate anonymous analytics events.
///
/// These values must be generated by the app. They must never contain an email,
/// player name, phone number, advertising identifier, or Firebase user id. They
/// are intentionally logged as event parameters instead of user properties.
@immutable
class AnalyticsCorrelation {
  const AnalyticsCorrelation({this.anonymousMatchId, this.anonymousSessionId});

  final String? anonymousMatchId;
  final String? anonymousSessionId;

  Map<String, Object> get parameters {
    final result = <String, Object>{};
    if (anonymousMatchId case final value?) {
      result['match_ref'] = _validatedAnonymousReference(
        value,
        'anonymousMatchId',
      );
    }
    if (anonymousSessionId case final value?) {
      result['app_session_ref'] = _validatedAnonymousReference(
        value,
        'anonymousSessionId',
      );
    }
    return result;
  }
}

/// Shared, non-identifying context for events that belong to a match.
@immutable
class MatchAnalyticsContext {
  const MatchAnalyticsContext({
    required this.playType,
    required this.mode,
    this.matchFormat,
    this.correlation = const AnalyticsCorrelation(),
  });

  final MatchPlayType playType;
  final GameMode mode;
  final MatchFormat? matchFormat;
  final AnalyticsCorrelation correlation;

  Map<String, Object> get parameters => <String, Object>{
    'play_type': playType.name,
    'game_mode': _gameModeName(mode),
    if (matchFormat case final value?) 'match_format': value.name,
    ...correlation.parameters,
  };
}

/// A typed event that can be sent to the game's analytics destination.
abstract interface class GameAnalyticsEvent {
  String get eventName;

  Map<String, Object> get parameters;
}

/// One anonymous step in the Quick Pop or Quick Table online funnel.
///
/// The event deliberately accepts only enums, numeric elapsed time and the
/// existing opaque correlation references. Room codes, player names, Firebase
