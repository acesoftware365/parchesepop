  final OnlineFlowStage stage;
  final MatchLaunchSource launchSource;
  final int? elapsedMilliseconds;
  final OnlineJoinMethod? joinMethod;
  final OnlineFlowFailureReason? failureReason;
  final OnlineRoomAccess? roomAccess;
  final AnalyticsCorrelation correlation;

  @override
  String get eventName => _onlineFlowEventName(experience, stage);

  @override
  Map<String, Object> get parameters => <String, Object>{
    'online_experience': experience.name,
    'flow_stage': stage.name,
    'launch_source': launchSource.name,
    'elapsed_milliseconds': ?elapsedMilliseconds,
    if (joinMethod case final value?) 'join_method': value.name,
    if (failureReason case final value?) 'failure_reason': value.name,
    if (roomAccess case final value?) 'room_access': value.name,
    ...correlation.parameters,
  };
}

