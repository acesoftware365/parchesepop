const String analyticsCollectionPreferenceKey =
    'privacy_analytics_collection_enabled';
const String analyticsFirstSeenAtPreferenceKey = 'analytics_first_seen_at_ms';
const String analyticsLastSessionAtPreferenceKey =
    'analytics_last_session_at_ms';

/// Records a 30-minute anonymous app session for opted-in players.
///
/// The first-seen timestamp stays on the device and is used only to derive a
/// coarse D1/D7 retention milestone. Collection remains strictly opt-in: when
/// [analytics] does not expose an enabled [AnalyticsPrivacyControl], no event
/// and no last-session marker are written.
Future<void> recordAppSessionAnalytics(
  GameAnalytics analytics, {
  required String anonymousSessionId,
  SharedPreferences? preferences,
  DateTime? now,
}) async {
  try {
    await _recordAppSessionAnalytics(
      analytics,
      anonymousSessionId: anonymousSessionId,
      preferences: preferences,
      now: now,
    );
  } catch (error, stackTrace) {
    // Session measurement must never delay or prevent the app from opening.
    // Keep diagnostics generic because storage errors can include local paths.
    debugPrint(
      'Anonymous session analytics was skipped (${error.runtimeType}).',
    );
    debugPrintStack(stackTrace: stackTrace);
  }
}

Future<void> _recordAppSessionAnalytics(
  GameAnalytics analytics, {
  required String anonymousSessionId,
  SharedPreferences? preferences,
  DateTime? now,
}) async {
  final store = preferences ?? await SharedPreferences.getInstance();
  final moment = (now ?? DateTime.now()).toUtc();
  var firstSeenAtMs = store.getInt(analyticsFirstSeenAtPreferenceKey);
  if (firstSeenAtMs == null || firstSeenAtMs > moment.millisecondsSinceEpoch) {
    firstSeenAtMs = moment.millisecondsSinceEpoch;
    await store.setInt(analyticsFirstSeenAtPreferenceKey, firstSeenAtMs);
  }

  // Session delivery fails closed. A no-op or legacy logger cannot prove that
  // collection is both available and explicitly enabled, so it must not write
  // the last-session idempotency marker either.
  final AnalyticsPrivacyControl? privacyControl =
      analytics is AnalyticsPrivacyControl
      ? analytics as AnalyticsPrivacyControl
      : null;
  if (privacyControl == null || !privacyControl.analyticsCollectionEnabled) {
    return;
  }

  final lastSessionAtMs = store.getInt(analyticsLastSessionAtPreferenceKey);
  if (lastSessionAtMs != null) {
    final timeSinceLastSession = moment.difference(
      DateTime.fromMillisecondsSinceEpoch(lastSessionAtMs, isUtc: true),
    );
    if (!timeSinceLastSession.isNegative &&
        timeSinceLastSession < const Duration(minutes: 30)) {
      return;
    }
  }

  final firstSeen = DateTime.fromMillisecondsSinceEpoch(
    firstSeenAtMs,
    isUtc: true,
  );
  final firstSeenDay = DateTime.utc(
    firstSeen.year,
    firstSeen.month,
    firstSeen.day,
  );
  final currentDay = DateTime.utc(moment.year, moment.month, moment.day);
  final daysSinceFirstSeen = currentDay.difference(firstSeenDay).inDays;
  final milestone = switch (daysSinceFirstSeen) {
    0 => RetentionMilestone.day0,
    1 => RetentionMilestone.day1,
    7 => RetentionMilestone.day7,
    _ => RetentionMilestone.returning,
  };
  await analytics.logEvent(
    AppSessionStartedEvent(
      daysSinceFirstSeen: daysSinceFirstSeen,
      milestone: milestone,
      isFirstAnalyticsSession: lastSessionAtMs == null,
      correlation: AnalyticsCorrelation(anonymousSessionId: anonymousSessionId),
    ),
  );
  await store.setInt(
    analyticsLastSessionAtPreferenceKey,
    moment.millisecondsSinceEpoch,
  );
}

/// Explicit opt-in control for anonymous product analytics.
///
/// Collection defaults to off. Advertising consent is intentionally separate
/// because declining analytics must never affect the ability to play or to
/// manage AdMob privacy choices.
abstract interface class AnalyticsPrivacyControl {
  bool get analyticsCollectionEnabled;

  Future<void> setAnalyticsCollectionEnabled(bool enabled);
}

typedef AnalyticsCollectionApplier = Future<void> Function(bool enabled);

class ConsentManagedGameAnalytics
    implements TypedGameAnalytics, AnalyticsPrivacyControl {
  ConsentManagedGameAnalytics({
    required GameAnalytics delegate,
    required SharedPreferences preferences,
    required bool enabled,
    AnalyticsCollectionApplier? applyPlatformCollection,
  }) : _delegate = delegate,
       _preferences = preferences,
       _enabled = enabled,
       _applyPlatformCollection =
           applyPlatformCollection ?? ((_) => Future<void>.value());

  final GameAnalytics _delegate;
  final SharedPreferences _preferences;
  final AnalyticsCollectionApplier _applyPlatformCollection;
  bool _enabled;

  @override
  bool get analyticsCollectionEnabled => _enabled;

  @override
  Future<void> setAnalyticsCollectionEnabled(bool enabled) async {
    if (_enabled == enabled) return;
    await _applyPlatformCollection(enabled);
    final saved = await _preferences.setBool(
      analyticsCollectionPreferenceKey,
      enabled,
    );
    if (!saved) {
      await _applyPlatformCollection(_enabled);
      throw StateError('Analytics privacy preference was not persisted.');
    }
    _enabled = enabled;
  }

  @override
  Future<void> logEvent(GameAnalyticsEvent event) =>
      _enabled ? _delegate.logEvent(event) : Future<void>.value();

  @override
  Future<void> logMatchStarted(MatchStartEvent event) =>
      _enabled ? _delegate.logMatchStarted(event) : Future<void>.value();
}

/// Lets code that still receives [GameAnalytics] send new typed events safely.
///
/// Legacy implementations ignore new event types, but continue to receive
/// [MatchStartEvent] through the original API.
extension TypedGameAnalyticsCompatibility on GameAnalytics {
  Future<void> logEvent(GameAnalyticsEvent event) {
    final analytics = this;
    if (analytics is TypedGameAnalytics) {
      return analytics.logEvent(event);
    }
    if (event is MatchStartEvent) {
      return analytics.logMatchStarted(event);
    }
    return Future<void>.value();
  }
}

/// Minimal destination abstraction for deterministic analytics tests.
abstract interface class GameAnalyticsSink {
  Future<void> log({
    required String eventName,
    required Map<String, Object> parameters,
  });
}

class NoopGameAnalytics implements TypedGameAnalytics {
  const NoopGameAnalytics();

  @override
  Future<void> logEvent(GameAnalyticsEvent event) async {}

  @override
  Future<void> logMatchStarted(MatchStartEvent event) async {}
}

/// Analytics implementation that accepts an injectable destination.
///
/// Logging errors are contained here so analytics can never interrupt a match.
class SinkGameAnalytics implements TypedGameAnalytics {
  const SinkGameAnalytics(this._sink);

  final GameAnalyticsSink _sink;

  @override
  Future<void> logMatchStarted(MatchStartEvent event) => logEvent(event);

  @override
  Future<void> logEvent(GameAnalyticsEvent event) async {
    try {
      final parameters = event.parameters;
      _validateAnalyticsPayload(event.eventName, parameters);
      await _sink.log(eventName: event.eventName, parameters: parameters);
    } catch (error, stackTrace) {
      // Do not interpolate the event name, rejected parameter value, or error
      // text here. Validation errors can originate from accidental PII, and
      // ArgumentError.toString() normally includes its rejected value.
      debugPrint('Analytics event was not recorded (${error.runtimeType}).');
      debugPrintStack(stackTrace: stackTrace);
    }
  }
}

class FirebaseGameAnalytics extends SinkGameAnalytics {
  FirebaseGameAnalytics(FirebaseAnalytics analytics)
    : super(_FirebaseGameAnalyticsSink(analytics));
}

class _FirebaseGameAnalyticsSink implements GameAnalyticsSink {
  const _FirebaseGameAnalyticsSink(this._analytics);

  final FirebaseAnalytics _analytics;

  @override
  Future<void> log({
    required String eventName,
    required Map<String, Object> parameters,
  }) {
    return _analytics.logEvent(name: eventName, parameters: parameters);
  }
}

Future<GameAnalytics> initializeGameAnalytics() async {
  if (kIsWeb ||
      (defaultTargetPlatform != TargetPlatform.android &&
          defaultTargetPlatform != TargetPlatform.iOS &&
          defaultTargetPlatform != TargetPlatform.macOS)) {
    return const NoopGameAnalytics();
  }

  try {
    final preferences = await SharedPreferences.getInstance();
    final collectionEnabled =
        preferences.getBool(analyticsCollectionPreferenceKey) ?? false;
    if (Firebase.apps.isEmpty) {
      await Firebase.initializeApp(
        options: DefaultFirebaseOptions.currentPlatform,
      );
    }
    final firebaseAnalytics = FirebaseAnalytics.instance;
    await firebaseAnalytics.setAnalyticsCollectionEnabled(collectionEnabled);
    return ConsentManagedGameAnalytics(
      delegate: FirebaseGameAnalytics(firebaseAnalytics),
      preferences: preferences,
      enabled: collectionEnabled,
      applyPlatformCollection: firebaseAnalytics.setAnalyticsCollectionEnabled,
    );
  } catch (error, stackTrace) {
    debugPrint('Google Analytics initialization was skipped: $error');
    debugPrintStack(stackTrace: stackTrace);
    return const NoopGameAnalytics();
  }
}

