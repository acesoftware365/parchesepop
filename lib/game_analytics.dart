String _validatedAnonymousReference(String value, String argumentName) {
  final kind = switch (argumentName) {
    'anonymousMatchId' => _AnonymousReferenceKind.match,
    'anonymousSessionId' => _AnonymousReferenceKind.session,
    'anonymousTransactionId' => _AnonymousReferenceKind.transaction,
    _ => null,
  };
  if (kind == null || !_isOpaqueAnonymousReference(value, kind)) {
    throw ArgumentError(
      'Must be an app-generated opaque analytics reference.',
      argumentName,
    );
  }
  return value;
}

String _validatedCatalogIdentifier(String value) {
  if (!_isSafeIdentifier(value, maximumLength: 64)) {
    throw ArgumentError('Must be a valid catalog identifier.', 'productId');
  }
  return value;
}

enum _AnonymousReferenceKind { match, session, transaction }

const Map<_AnonymousReferenceKind, List<String>> _anonymousReferencePrefixes =
    <_AnonymousReferenceKind, List<String>>{
      _AnonymousReferenceKind.match: <String>[
        'match_',
        'cpu_match_',
        'online_match_',
        'restored_match_',
        'resume_match_',
        'resume_',
        'quick-',
      ],
      _AnonymousReferenceKind.session: <String>[
        'session_',
        'shop_session_',
        'tutorial_session_',
      ],
      _AnonymousReferenceKind.transaction: <String>[
        'transaction_',
        'reward_transaction_',
        'shop_transaction_',
      ],
    };

bool _isOpaqueAnonymousReference(String value, _AnonymousReferenceKind kind) {
  if (!_isSafeIdentifier(value, maximumLength: 64)) return false;
  return _anonymousReferencePrefixes[kind]!.any(
    (prefix) => value.startsWith(prefix) && value.length > prefix.length,
  );
}

bool _isSafeIdentifier(String value, {required int maximumLength}) {
  if (value.isEmpty || value.length > maximumLength) return false;
  for (final codeUnit in value.codeUnits) {
    final isDigit = codeUnit >= 48 && codeUnit <= 57;
    final isUppercase = codeUnit >= 65 && codeUnit <= 90;
    final isLowercase = codeUnit >= 97 && codeUnit <= 122;
    final isSeparator = codeUnit == 45 || codeUnit == 95;
    if (!isDigit && !isUppercase && !isLowercase && !isSeparator) {
      return false;
    }
  }
  return true;
}

