void _validateAnalyticsPayload(
  String eventName,
  Map<String, Object> parameters,
) {
  if (eventName.isEmpty ||
      eventName.length > 40 ||
      !_isSafeIdentifier(eventName, maximumLength: 40) ||
      eventName.startsWith('firebase_') ||
      eventName.startsWith('google_') ||
      eventName.startsWith('ga_')) {
    throw ArgumentError('Invalid analytics event name.', 'eventName');
  }
  if (parameters.length > 25) {
    throw ArgumentError(
      'Analytics payload exceeds the parameter limit.',
      'parameters',
    );
  }
  for (final entry in parameters.entries) {
    if (!_allowedParameterNames.contains(entry.key)) {
      throw ArgumentError(
        'Analytics payload contains a parameter outside the allowlist.',
        'parameters',
      );
    }
    final value = entry.value;
    if (value is! String && value is! int && value is! double) {
      throw ArgumentError(
        'Analytics payload contains an unsupported value type.',
        'parameters',
      );
    }
    if (value is String && value.length > 100) {
      throw ArgumentError(
        'Analytics payload contains an oversized string value.',
        'parameters',
      );
    }
    final referenceKind = switch (entry.key) {
      'match_ref' => _AnonymousReferenceKind.match,
      'app_session_ref' => _AnonymousReferenceKind.session,
      'transaction_ref' => _AnonymousReferenceKind.transaction,
      _ => null,
    };
    if (referenceKind != null &&
        (value is! String ||
            !_isOpaqueAnonymousReference(value, referenceKind))) {
      throw ArgumentError(
        'Analytics payload contains an invalid opaque reference.',
        'parameters',
      );
    }
    if (entry.key == 'product_id' &&
        (value is! String || !_isSafeIdentifier(value, maximumLength: 64))) {
      throw ArgumentError(
        'Analytics payload contains an invalid catalog identifier.',
        'parameters',
      );
    }
  }
}
